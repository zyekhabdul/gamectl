#!/usr/bin/env bash
# ==============================================================================
# gamectl - Source to Standalone Binary Bundler
# Concatenates modular source files into a single zero-dependency executable.
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
OUTPUT_BIN="$REPO_ROOT/bin/gamectl"

# Source modules in strict dependency order
MODULES=(
    "$REPO_ROOT/src/core/00_header.sh"
    "$REPO_ROOT/src/core/10_utils.sh"
    "$REPO_ROOT/src/steam/20_discovery.sh"
    "$REPO_ROOT/src/steam/25_identity.sh"
    "$REPO_ROOT/src/steam/30_downloader.sh"
    "$REPO_ROOT/src/runners/40_wrappers.sh"
    "$REPO_ROOT/src/runners/50_launcher.sh"
    "$REPO_ROOT/src/diagnostics/60_doctor.sh"
    "$REPO_ROOT/src/tui/70_dashboard.sh"
    "$REPO_ROOT/src/main.sh"
)

# Verify that all module files exist
for mod in "${MODULES[@]}"; do
    if [ ! -f "$mod" ]; then
        echo "[ERROR] Missing source module: $mod" >&2
        exit 1
    fi
done

TMP_OUT="$(mktemp "${TMPDIR:-/tmp}/gamectl_bundle.XXXXXX")"
trap 'rm -f "$TMP_OUT"' EXIT

# Generate bundle header
cat <<'HEADER' > "$TMP_OUT"
#!/usr/bin/env bash
# ==============================================================================
# gamectl - Sovereign TUI Game Manager & Launcher (Standalone Bundle)
# Auto-generated by scripts/build.sh. Do not edit directly.
# Edit modular sources under src/ and run ./scripts/build.sh to recompile.
# ==============================================================================

HEADER

# Concatenate all modules, stripping redundant shebangs if present
for mod in "${MODULES[@]}"; do
    rel_path="${mod#"$REPO_ROOT/"}"
    cat <<EOF >> "$TMP_OUT"
# --- [MODULE] $rel_path ---
EOF
    grep -v '^#!/usr/bin/env bash' "$mod" >> "$TMP_OUT"
    echo >> "$TMP_OUT"
done

# Deterministic machine syntax check
if ! bash -n "$TMP_OUT"; then
    echo "[ERROR] Syntax validation failed on bundled artifact." >&2
    exit 1
fi

if [ "${1:-}" = "--check" ]; then
    if [ ! -f "$OUTPUT_BIN" ]; then
        echo "[FAIL] Target binary $OUTPUT_BIN does not exist." >&2
        exit 1
    fi
    if cmp -s "$TMP_OUT" "$OUTPUT_BIN"; then
        echo "[PASS] Binary is synchronized with modular sources."
        exit 0
    else
        echo "[FAIL] Binary is out of sync with modular sources. Run ./scripts/build.sh" >&2
        exit 1
    fi
fi

# Atomic install via POSIX rename(2) to prevent in-place truncation of running processes
DEST_DIR="$(dirname "$OUTPUT_BIN")"
mkdir -p "$DEST_DIR"
DEST_TMP="$(mktemp "${DEST_DIR}/.gamectl.tmp.XXXXXX")"
cp "$TMP_OUT" "$DEST_TMP"
chmod +x "$DEST_TMP"
mv -f "$DEST_TMP" "$OUTPUT_BIN"

# Synchronize python runner bundled binary if package directory exists
if [ -d "$REPO_ROOT/src/gamectl_runner" ]; then
    mkdir -p "$REPO_ROOT/src/gamectl_runner/bin"
    cp -p "$OUTPUT_BIN" "$REPO_ROOT/src/gamectl_runner/bin/gamectl"
fi

line_count=$(wc -l < "$OUTPUT_BIN" | tr -d ' ')
echo "[ VERIFIED ] gamectl compiled successfully -> bin/gamectl ($line_count lines, executable)"
